#!/usr/bin/env python3
"""Independently validate bounded Android Opus output and decode it on the host.

Container rules follow RFC3533 and RFC7845. This deliberately accepts only
the fresh, mono, mapping-family0 streams generated by the two owned fixtures.
Host decoder checks do not claim that Android MediaCodec was executed.
"""
